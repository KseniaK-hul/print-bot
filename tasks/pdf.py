# tasks/pdf.py — единственное место, где мы трогаем PDF.
#
# ПОЧЕМУ ЗДЕСЬ ТАК МАЛО КОДА. В старой версии тут был анализ цвета, который
# для каждой картинки создавал fitz.Pixmap — то есть распаковывал её в сырой
# RGB. Скан A0 в 300 dpi = 9933 x 14043 x 3 байта ≈ 400 МБ на ОДИН файл, и
# на сервере с 512 МБ процесс просто убивался. Это и была настоящая причина
# «бот умирает после N заказов»: дело было не в количестве заказов, а в том,
# что кто-то присылал тяжёлый чертёж.
#
# Теперь цвет спрашиваем у пользователя, а от PDF нужно только количество
# страниц — это чтение служебной таблицы документа, без рендеринга.
# ==========================================================================

import asyncio

import fitz

from config import logger

# Даже дешёвое открытие файла не пускаем толпой: несколько сотен страниц
# на медленном диске займут время, а лишние параллельные открытия ничего
# не ускорят.
_semaphore = asyncio.Semaphore(2)


def _count_pages_sync(path: str) -> int:
    try:
        with fitz.open(path) as doc:
            return doc.page_count
    except Exception as e:
        logger.warning("Не удалось прочитать PDF %s: %s", path, e)
        return 0


async def count_pages(path: str) -> int:
    """Количество страниц, 0 — если файл не читается."""
    async with _semaphore:
        return await asyncio.to_thread(_count_pages_sync, path)
